import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const command = process.argv[2];
if (!['dev', 'start'].includes(command)) throw new Error('Usage: node scripts/run-demo.mjs dev|start');
const next = fileURLToPath(new URL('../node_modules/next/dist/bin/next', import.meta.url));
const args = [next, command, ...(command === 'dev' ? ['--webpack'] : []), '--hostname', '127.0.0.1', ...process.argv.slice(3)];
console.log('TeamVault demo: simulated TideCloak identities; local SQLite data; no realm required.');
const child = spawn(process.execPath, args, { stdio: 'inherit', env: { ...process.env, TEAMVAULT_AUTH_MODE: 'demo' } });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
child.on('error', error => { console.error(error.message); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code ?? 1; });
